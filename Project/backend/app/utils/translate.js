export default function translate(surveyID, data) {
    if (!(surveyID in reference)) return data;
    let qbank = reference[surveyID];
    return Object.fromEntries(Object.entries(data).map(q => {
        if (!(q[0] in qbank))
            return null;
        let que = qbank[q[0]];
        if (!("name" in que))
            return null;
        return [que.name, q[1]];
    }).filter(tmp => Array.isArray(tmp) && tmp.length === 2))
}

SOCIAL_SVG.twitter = SOCIAL_SVG.x;

export default function SocialAuth() {
  const [providers, setProviders] = useState([]);

  useEffect(() => {
    api
      .post('/api/v1/auth/socials', {})
      .then((resp) => setProviders(resp?.data ?? []))
      .catch(() => setProviders([]));
  }, []);

  if (!providers.length) return null;

  const list = providers.map((p) => {
    const name = (p.name || '').toLowerCase();
    return {
      name,
      label: `Continue with ${name.charAt(0).toUpperCase() + name.slice(1)}`,
      icon: SOCIAL_SVG[name] || <Icon name="key" size={18} />,
      href: p.authUrl
    };
  });

  return (
    <div className="social-auth">
      <div className="social-divider">
        <span>or continue with</span>
      </div>
      {list.length <= 2 ? (
        <div className="social-list">
          {list.map((p) => (
            <a key={p.name} href={p.href} className="social-btn">
              <span className="social-ico">{p.icon}</span>
              {p.label}
            </a>
          ))}
        </div>
      ) : (
        <div className="social-icons">
          {list.map((p) => (
            <a key={p.name} href={p.href} className="social-icon-btn" title={p.label} aria-label={p.label}>
              <span className="social-ico">{p.icon}</span>
            </a>
          ))}
        </div>
      )}
    </div>
  );
}
import fs from 'fs';
const [,, file, out, label] = process.argv;
const L = fs.readFileSync(file, 'utf8').split('\n');
const find = (re, from = 0) => { for (let i = from; i < L.length; i++) if (re.test(L[i])) return i; return -1; };
const skip = find(/^\s+skip: "Skip/);
let strStart = skip; while (!/var [A-Za-z0-9_$]+ = \{\s*$/.test(L[strStart])) strStart--;
// object literal: read from "{" balancing braces
function grab(lineIdx, opener) {
  const text = L.slice(lineIdx).join('\n');
  const st = text.indexOf(opener);
  let d = 0, inS = null, esc = false;
  for (let i = st; i < text.length; i++) {
    const c = text[i];
    if (inS) { if (esc) esc = false; else if (c === '\\') esc = true; else if (c === inS) inS = null; continue; }
    if (c === '"' || c === "'" || c === '`') { inS = c; continue; }
    if (c === '{' || c === '[') d++;
    else if (c === '}' || c === ']') { d--; if (d === 0) return text.slice(st, i + 1); }
  }
}
const strings = eval('(' + grab(strStart, '{') + ')');
const chIdx = find(/var [A-Za-z0-9_$]+ = \[\s*$/, skip);
const chapters = eval('(' + grab(chIdx, '[') + ')');
const secIdx = find(/^\s+[A-Za-z0-9_$]+ = \{\s*$/, chIdx + 1);
const sections = eval('(' + grab(secIdx, '{') + ')');
const csIdx = find(/^\s+: \[\s*$/, secIdx);
const consents = eval('(' + grab(csIdx, '[') + ')');
const cfgIdx = find(/termsVersion: "/);
const cfgText = L.slice(cfgIdx, cfgIdx + 12).join('\n');
const pick = (k) => (cfgText.match(new RegExp(k + ':\\s*"([^"]*)"')) || [])[1];
const opMatch = cfgText.match(/operator:\s*"([^"]*)"/);
const data = {
  source: `public/user/${file.split('/').pop()} (approved panel agreement, copied word for word)`,
  termsVersion: pick('termsVersion'), effectiveDate: pick('effectiveDate'), lastUpdated: pick('lastUpdated'),
  operator: opMatch && opMatch[1], supportEmail: pick('supportEmail'), address: pick('address'),
  strings, chapters: chapters.map(({ id, icon, sections }) => ({ id, icon, sections })), sections, consents
};
fs.writeFileSync(out, `// GENERATED by scripts/extract-consent.mjs from the approved ${label} panel agreement.\n// Do not edit the legal wording here: change the source agreement and re-run the script.\nexport default ${JSON.stringify(data, null, 1)};\n`);
